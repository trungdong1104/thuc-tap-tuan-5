export const LOW_STOCK_THRESHOLD = 5;

export function resolveProductStatus(quantity) {
  if (quantity <= 0) return 'OUT_OF_STOCK';
  if (quantity <= LOW_STOCK_THRESHOLD) return 'LOW_STOCK';
  return 'IN_STOCK';
}

